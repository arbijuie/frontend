function withShortVenue(opportunity: ReturnType<typeof makeOpportunity>, venue: string) {
  return {
    ...opportunity,
    legs: opportunity.legs.map((leg) => (leg.side === "short" ? { ...leg, venue } : leg)),
  };
}

